// Нормализация текстового запроса в ключ кэша блюд (этап 2).
//
// Цель: «Борщ!», «  борщ  », «борщ» → один и тот же ключ, чтобы cache hit
// срабатывал независимо от регистра, лишних пробелов, пунктуации и эмодзи.
// Чистая функция без DOM/сети — используется на сервере (поиск, прогрев) и
// покрыта юнит-тестами (queryNormalize.test.ts).

// Предел длины ключа = ограничению колонки dish_cache.query_key (200).
export const MAX_QUERY_KEY_LENGTH = 200;

export function normalizeQueryKey(query: unknown): string {
  if (typeof query !== "string") return "";
  return (
    query
      .toLowerCase()
      // Оставляем только буквы (любых алфавитов), цифры и пробелы. Пунктуация,
      // эмодзи и прочие символы → пробел (чтобы «борщ,суп» не склеился в
      // «боршсуп», а распался на слова, которые дальше схлопнутся). Пробел, а
      // не удаление, важен именно для разделителей.
      .replace(/[^\p{L}\p{N}\s]/gu, " ")
      // Схлопываем любые пробельные последовательности в один пробел.
      .replace(/\s+/g, " ")
      .trim()
      .slice(0, MAX_QUERY_KEY_LENGTH)
      // Повторный trim на случай, если slice отрезал ровно по пробелу.
      .trim()
  );
}
