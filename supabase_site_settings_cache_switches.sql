-- АВАРИЙНЫЕ РУБИЛЬНИКИ КЭША: две колонки в site_settings.
--
-- Прогнать в Supabase SQL Editor ДО мержа кода. Код читает строку целиком
-- (select=*), поэтому до миграции он не падает, а просто видит обе новые
-- настройки выключенными — но и вылечить застрявший кэш до миграции нечем.
--
-- RLS НЕ ТРОГАЕМ. Политики на site_settings уже стоят и остаются как есть
-- (см. supabase_admin_tables_rls.sql):
--   * SELECT открыт для anon — иначе middleware (proxy.ts) не прочитает
--     режим обслуживания на анонимном ключе;
--   * UPDATE для anon/authenticated заблокирован restrictive-политикой —
--     писать может только service_role из /api/admin/*.
-- Новые колонки наследуют ровно эти правила: читать может кто угодно (в них
-- нет ничего секретного — это метка версии и булев флаг), писать — только
-- админка.
--
-- ЗАЧЕМ ЭТО ВООБЩЕ НУЖНО. 5 сентября сломанная версия приехала людям в кэш, и
-- вылечить её удалённо было нечем: сервис-воркер собран с skipWaiting: false,
-- то есть новая версия ждёт, пока закроется последний клиент. В standalone на
-- iOS документ замораживается, а не закрывается, и ждать можно сутками.
-- Эти две колонки — рычаги, до которых можно дотянуться из админки за секунды.

alter table public.site_settings
  -- УРОВЕНЬ B. Метка поколения кэша. Любое НОВОЕ значение (обычно просто
  -- текущая дата-время) означает для клиента: «выброси всё, что лежит в
  -- Cache API, и перерегистрируй сервис-воркер».
  --
  -- ВАЖНО, ЧТО ЭТО НЕ ДЕЛАЕТ: localStorage не трогается. Списки покупок,
  -- закрепления, вкусовой профиль и сессия остаются на месте. Чистятся только
  -- кэши воркера — см. components/CacheKillSwitch.tsx.
  --
  -- text, а не число: значение нигде не сравнивается на «больше/меньше», нужен
  -- только факт «отличается от того, что клиент видел прошлый раз».
  add column if not exists cache_epoch text,

  -- УРОВЕНЬ C. Просьба к браузеру почистить свой HTTP-кэш: proxy.ts начинает
  -- отдавать заголовок Clear-Site-Data: "cache" на навигациях.
  --
  -- ТОЛЬКО "cache". Значение "storage", которое умеет убивать и сервис-воркер,
  -- мы не используем НИКОГДА: вместе с воркером оно стирает localStorage, то
  -- есть списки покупок живых людей. Данные пользователей не удаляем.
  -- Из-за этого уровень C слабее уровня B и работает как третья линия. Зато
  -- это единственный рубильник, который действует в iOS-оболочке: там
  -- сервис-воркера нет вовсе (см. шапку next.config.ts), а HTTP-кэш WKWebView
  -- есть, и чистится он ровно этим заголовком.
  add column if not exists purge_client_cache boolean not null default false;

