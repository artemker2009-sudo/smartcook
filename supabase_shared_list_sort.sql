-- 1) Аноним по-прежнему не читает список — и новые колонки в том числе.
--    Ожидаем [] (а не строки и не ошибку про несуществующую колонку: колонка
--    есть, просто RLS не отдаёт ни одной строки).
--   curl -s "$SB_URL/rest/v1/shared_lists?select=id,sort_sig,sort_groups" \
--     -H "apikey: $SB_KEY" -H "Authorization: Bearer $SB_KEY"
--   # ожидаем: []
--
-- 2) Аноним не может подсунуть свою раскладку в чужой список.
--    Ожидаем 401/403 с "row-level security", НЕ 204 и НЕ 200.
--   curl -s -X PATCH "$SB_URL/rest/v1/shared_lists?id=eq.<любой id>" \
--     -H "apikey: $SB_KEY" -H "Authorization: Bearer $SB_KEY" \
--     -H "Content-Type: application/json" \
--     -d '{"sort_groups":[{"department":"Взлом","items":["ха"]}]}'
--
--    ВНИМАНИЕ на ответ 204: он тоже нормален и означает «изменено 0 строк» —
--    RLS просто не показал анониму ни одной строки, менять было нечего. Это
--    НЕ пробой. Чтобы убедиться, сверьте данные сервис-ролью: sort_groups
--    должен остаться прежним (или null).
--
-- 3) Пока роут раскладки общего списка не написан, колонки просто пустые и ни
