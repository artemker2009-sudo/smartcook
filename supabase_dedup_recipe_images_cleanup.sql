-- ЧИСТКА ДУБЛЕЙ КАРТИНОК БЛЮД (одноразовый скрипт, прогоняется ВРУЧНУЮ).
--
-- Контекст: в таблице recipes одна строка = один поиск (история пользователя),
-- поэтому одно популярное блюдо имеет много строк. При генерации/переиспользовании
-- картинок несколько строк одного блюда получили image_url → в админ-галерее
-- блюдо двоилось. Цель: оставить по ОДНОЙ строке-с-картинкой на нормализованное
-- блюдо, у остальных обнулить image_url. САМИ строки-истории НЕ удаляем.
--
-- Как запускать (в Supabase SQL Editor, вручную, ДО мержа кода):
--   1) Выполнить БЛОК 1 (SELECT) — убедиться, что список ровно тот, что ждём (16 строк).
--   2) Выполнить БЛОК 2 (UPDATE) — обнулить image_url по этим 16 id.
--   3) Выполнить БЛОК 3 (SELECT) — увидеть реально осиротевший файл (по факту 1 шт.).
--   4) БЛОК 4 — удалить этот файл НЕ SQL-ом, а через Storage UI/API (Supabase
--      запрещает прямой delete из storage.objects). Шаг опциональный.
-- Никаких каскадов вслепую: UPDATE — по явному списку id.
--
-- ВАЖНО: чистка данных НЕ обязательна для «1 блюдо = 1 картинка» — это уже
-- обеспечивает код (дедуп галереи и кандидатов в admin-роуте). БЛОК 2 — лишь
-- гигиена данных. Учти: 15 из 16 обнуляемых строк ссылались на ВАЛИДНЫЕ общие
-- картинки из dish_cache — обнуление уберёт картинку у этих строк-историй в
-- личной истории тех пользователей (сама картинка блюда остаётся у «оставленной»
-- строки и в dish_cache). Единственная по-настоящему лишняя картинка-файл —
-- 1543.webp (второй файл для «Арбузные дольки»; оставляем 1544.webp).
--
-- Схему НЕ меняем: новых таблиц/индексов нет (уникальность блюда живёт в
-- dish_cache.query_key, в recipes дубли строк легитимны). Поэтому миграции с
-- UNIQUE и правок RLS здесь нет — только DML над существующими строками.
--
-- Списки id получены разведкой (нормализация названия = lib/queryNormalize):
--   • оставляем по 1 строке на блюдо (правило: макс. likes → новее → меньший id);
--   • обнуляем ровно 16 «лишних» строк (перечислены явно ниже).

-- ── БЛОК 1. ПРОВЕРКА: 16 строк, у которых обнулим image_url ────────────────────
-- Ожидаем ровно 16 строк. Столбцы: id, нормализованное блюдо, текущий image_url.
select id, title, image_url
from public.recipes
where id in (1543,1570,1571,1575,1576,1577,1578,1579,1580,1582,1584,1585,1596,1597,1599,1600)
order by id;

-- Для контекста — какие строки ОСТАЮТСЯ с картинкой (по одной на блюдо, 13 шт.):
--   select id, title, image_url from public.recipes
--    where id in (1544,1545,1546,1547,1568,1573,1581,1583,1591,1593,1595,1601,1603)
--    order by id;

-- ── БЛОК 2. ОБНУЛЕНИЕ image_url у 16 лишних строк ─────────────────────────────
-- Строки-истории остаются, обнуляется только ссылка на картинку. После этого
-- блюдо в админ-галерее перестаёт двоиться и на уровне данных.
update public.recipes
   set image_url = null
 where id in (1543,1570,1571,1575,1576,1577,1578,1579,1580,1582,1584,1585,1596,1597,1599,1600);
-- Ожидаемо затронуто строк: 16.

-- ── БЛОК 3. ПРОВЕРКА: какие файлы {id}.webp реально осиротели ─────────────────
-- ВАЖНО: из 16 обнулённых строк только 1543 имела СОБСТВЕННЫЙ файл 1543.webp.
-- Остальные 15 ссылались на ОБЩИЕ файлы dish-cache/*.webp (картинка из кэша
-- блюда), которые ещё используются оставшимися рецептами и таблицей dish_cache —
-- их удалять НЕЛЬЗЯ. Поэтому кандидат на удаление тут по факту один: 1543.webp.
-- Условие NOT EXISTS страхует: файл считается осиротевшим, только если на него
-- не ссылается НИ ОДНА оставшаяся строка recipes.image_url.
select o.name
from storage.objects o
where o.bucket_id = 'recipe-images'
  and o.name in ('1543.webp')
  and not exists (
    select 1 from public.recipes r
    where r.image_url like '%/' || o.name || '%'
  );

-- ── БЛОК 4. УДАЛЕНИЕ осиротевшего файла из Storage ───────────────────────────
-- ВНИМАНИЕ: прямой `delete from storage.objects` в Supabase ЗАПРЕЩЁН (триггер
-- storage.protect_delete, ошибка «42501: Direct deletion from storage tables is
-- not allowed. Use the Storage API instead»). Поэтому файл удаляем НЕ SQL-ом.
--
-- Это опциональная уборка: осиротевший файл (после БЛОКА 2) ни на что не влияет —
-- на него не ссылается ни одна строка, в галерее он не показывается. Можно удалить
-- для чистоты, можно оставить.
--
-- Как удалить 1543.webp (сначала выполни БЛОК 2, чтобы файл стал осиротевшим,
-- и БЛОК 3 — чтобы убедиться, что он больше не используется):
--   Вариант A (UI): Dashboard → Storage → бакет recipe-images → файл 1543.webp
--                   → «...» → Delete.
--   Вариант B (Storage API, service_role, с сервера):
--     await supabase.storage.from('recipe-images').remove(['1543.webp']);
--
-- Прочие 15 обнулённых строк ссылались на ОБЩИЕ dish-cache/*.webp, которые ещё
-- используются — их файлы НЕ трогаем.
