-- ЛИШНЯЯ РАЗРЕШАЮЩАЯ INSERT-ПОЛИТИКА НА recipes (найдено рантайм-приёмкой PR 1).
--
-- ЭТОТ ФАЙЛ НЕЗАВИСИМ от supabase_recipes_session_id_privacy.sql. Порядок между
-- ними любой; можно прогнать только этот, можно только тот.
--
-- ЧТО ОБНАРУЖЕНО (проверено запросами к боевому PostgREST 2026-09-19, на
-- собственных временных строках, которые тут же удалены):
--   * RLS на recipes ВКЛЮЧЁН и работает: anon UPDATE чужой строки -> 0 строк,
--     значение не изменилось; anon DELETE -> строка осталась жива.
--   * НО anon INSERT со session_id чужого РЕАЛЬНОГО аккаунта -> HTTP 201.
--     То есть кто угодно с публичным анон-ключом может писать строки в чужую
--     историю рецептов.
--   * Функция public.is_registered_user_id исправна: на реальный uid отдаёт
--     true, на гостевой — false. Значит дело НЕ в ней.
--
-- Отсюда вывод: кроме политики "Insert own recipes" из
-- supabase_recipes_social_rls.sql на таблице живёт ЕЩЁ ОДНА permissive-политика
-- для INSERT, более старая и разрешающая. Permissive-политики складываются по
-- ИЛИ, поэтому строгая проверка ничего не значит, пока рядом есть широкая.
-- Прошлый файл дропал политику ПО ИМЕНИ ("Insert own recipes"), поэтому старая
-- политика с другим именем пережила ту чистку.
--
-- ПОЧЕМУ ЭТО ВАЖНО СЕЙЧАС. Это ровно вектор инцидента №2 (массовая запись в
-- recipes), только со стороны INSERT, и он же обесценивает защиту переноса
-- гостевых рецептов в PR 2: проверять владельца при UPDATE бессмысленно, если
-- подкинуть строку в чужую историю можно бесплатно и анонимно.
--
-- РЕШЕНИЕ. Снести ВСЕ INSERT-политики на recipes (не по именам, а перечислением
-- из каталога — именно на этом прошлый раз и споткнулись) и создать заново
-- ровно одну, ту же самую по смыслу.


-- ============================================================================
-- 0) ДО. Посмотреть, что реально лежит на таблице. Результат этого запроса
--    стоит сохранить: он объясняет, что именно дропнул шаг 1.
-- ============================================================================
select policyname, cmd, permissive, roles, qual, with_check
from pg_policies
where schemaname = 'public' and tablename = 'recipes'
order by cmd, policyname;


-- ============================================================================
-- 1) Снос всех INSERT-политик на public.recipes.
--    Через каталог, а не по именам: имя старой политики нам неизвестно, и
--    повторять ошибку «дропнули только знакомое» нельзя.
-- ============================================================================
do $$
declare
  pol record;
begin
  for pol in
    select policyname
    from pg_policies
    where schemaname = 'public' and tablename = 'recipes' and cmd = 'INSERT'
  loop
    execute format('drop policy %I on public.recipes', pol.policyname);
    raise notice 'dropped insert policy: %', pol.policyname;
  end loop;
end $$;


-- ============================================================================
-- 2) Единственная правильная INSERT-политика (текст — из
--    supabase_recipes_social_rls.sql, менять смысл не требуется):
--      * залогиненный пишет только под своим auth.uid();
--      * гость (без JWT) пишет только под идентификатором, который НЕ
--        принадлежит ни одному реальному аккаунту.
--    Гостевые сохранения рецептов без регистрации при этом продолжают работать —
--    это легитимный и основной сценарий приложения.
-- ============================================================================
create policy "Insert own recipes"
on public.recipes
for insert
to anon, authenticated
with check (
  (auth.uid() is not null and auth.uid()::text = session_id)
  or (auth.uid() is null and not public.is_registered_user_id(session_id))
);


-- ============================================================================
-- 3) ПОСЛЕ. Ожидаем ровно одну строку с cmd='INSERT'.
-- ============================================================================
select policyname, cmd, permissive, roles, with_check
from pg_policies
where schemaname = 'public' and tablename = 'recipes'
order by cmd, policyname;


