/** Разряд числа: сотни, десятки, единицы. Нужен для сборки составных. */
function scaleOf(value: number): number {
  if (value >= 100) return 100;
  if (value >= 20) return 10;
  return 1;
}

/** Число цифрами так, как его пишут в рецептах: «1,5», а не «1.5». */
function formatNumber(value: number): string {
  return Number.isInteger(value) ? String(value) : String(value).replace(".", ",");
}

/**
 * Меры: время, размер, температура. Единицы из словаря покупок (ложка, стакан,
 * грамм, щепотка…) добавляются к ним ниже.
 */
const MEASURE_WORDS = [
  "минута", "минуты", "минут", "час", "часа", "часов", "секунда", "секунд",
  "день", "дня", "дней", "сутки", "неделя", "недели", "месяц",
  "сантиметр", "сантиметра", "сантиметров", "см", "миллиметр", "мм",
  "градус", "градуса", "градусов",
];

/**
 * Не меры, но рядом с ними число — всё ещё количество: посуда, счётные слова,
 * куски и стороны.
 */
const COUNTABLE_WORDS = [
  "часть", "части", "частей", "половина", "треть", "четверть",
  "сторона", "стороны", "сторон", "слой", "слоя", "ряд", "ряда",
  "раз", "раза", "порция", "порции", "порций", "человек", "персона", "персоны",
  "противень", "сковорода", "сковороды", "сковороде", "кастрюля", "тарелка",
  "миска", "форма", "формы", "лист", "листа", "листьев", "веточка", "веточки",
  "зубок", "долька", "дольки", "капля", "капель", "щепоть",
];

const MEASURE_STEMS = new Set([...UNIT_WORDS, ...MEASURE_WORDS].map(stem));
const HEAD_STEMS = new Set([...MEASURE_STEMS, ...[...PRODUCT_WORDS, ...COUNTABLE_WORDS].map(stem)]);

/** Слово в том виде, в каком его ищут в словарях: нижний регистр, ё→е. */
function normalize(word: string): string {
  return word.toLowerCase().replace(/ё/g, "е");
}

/** Сколько слов-описаний разрешено перешагнуть до предмета. */
const MAX_ADJECTIVES = 2;

export type NumeralReplacement = {
  /** Слово, как оно стояло в тексте. */
  from: string;
  /** Чем заменено. */
  to: string;
  /** Предмет, из-за которого замена признана количеством. */
  head: string;
  /** Кусок текста вокруг замены — для отчёта на проверку. */
  context: string;
};

export type NumeralsResult = {
  text: string;
  replacements: NumeralReplacement[];
};

const WORD_RE = /[А-Яа-яЁёA-Za-z]+/g;

/** Короткий кусок текста вокруг замены — чтобы решение было видно в отчёте. */
function contextAround(text: string, start: number, end: number): string {
  const from = Math.max(0, start - 30);
  const to = Math.min(text.length, end + 30);
  return (from > 0 ? "…" : "") + text.slice(from, to).replace(/\s+/g, " ").trim() + (to < text.length ? "…" : "");
}

/**
 * Заменяет количественные числительные на цифры.
 *
 * Чистая функция: ничего не читает и не пишет, поэтому её поведение
 * проверяется тестами, а не прогоном по боевой базе.
 */
export function numeralsToDigits(text: string): NumeralsResult {
  if (typeof text !== "string" || !text) return { text: typeof text === "string" ? text : "", replacements: [] };

  const words = [...text.matchAll(WORD_RE)].map((m) => ({
    raw: m[0],
    key: normalize(m[0]),
    start: m.index ?? 0,
    end: (m.index ?? 0) + m[0].length,
  }));

  const replacements: NumeralReplacement[] = [];
  const edits: Array<{ start: number; end: number; value: string }> = [];

  for (let i = 0; i < words.length; i++) {
    const word = words[i];
    const first = NUMERALS[word.key];
    if (first === undefined) continue;

    // Составное числительное: «двести двадцать» — это 220, а не «двести 20».
    // Собираем, пока следующее слово идёт через ОДИН пробел и его разряд
    // меньше предыдущего: 200 → 20 → 5. Через дефис («пять–шесть») это уже не
    // составное число, а диапазон — каждое заменяется само по себе.
    let total = first;
    let last = i;
    let scale = scaleOf(first);
    while (Number.isInteger(total)) {
      const next = words[last + 1];
      if (!next) break;
      const value = NUMERALS[next.key];
      if (value === undefined || !Number.isInteger(value)) break;
      const separator = text.slice(words[last].end, next.start);
      if (!/^ +$/.test(separator)) break;
      const nextScale = scaleOf(value);
      if (nextScale >= scale) break;
      total += value;
      scale = nextScale;
      last = last + 1;
    }
    const digit = formatNumber(total);

    // Ищем предмет: перешагиваем соседние числительные («две-три ложки») и
    // слова-описания («одну столовую ложку»), но не больше двух подряд —
    // дальше это уже не то количество.
    let head: (typeof words)[number] | null = null;
    let skipped = 0;
    for (let j = last + 1; j < words.length && skipped <= MAX_ADJECTIVES; j++) {
      const next = words[j];
      // Слово из словаря — предмет, даже если по окончанию похоже на
      // прилагательное. Иначе «с одной ложкой сахара» перешагивало бы через
      // «ложкой» (окончание «-ой») к «сахару», и в отчёте на проверку стояло бы
      // не то слово, из-за которого сделана замена.
      if (HEAD_STEMS.has(stem(next.key))) {
        head = next;
        break;
      }
      if (NUMERALS[next.key] || looksLikeAdjective(next.key)) {
        skipped++;
        continue;
      }
      head = next;
      break;
    }
    if (!head || !HEAD_STEMS.has(stem(head.key))) continue;

    // Единицу заменяем цифрой ТОЛЬКО перед мерой: «1 час», «1 минуту»,
    // «1 ложка» — это количество, а «одна сковорода и полчаса времени», «в
    // одной сковороде», «в один слой» — это «единственная», «та же самая»,
    // «ровным слоем». Цифра там превращает живую фразу в накладную. Отличить
    // одно от другого можно ровно по тому, мера ли стоит следом.
    if (total === 1 && !MEASURE_STEMS.has(stem(head.key))) continue;

    const end = words[last].end;
    edits.push({ start: word.start, end, value: digit });
    replacements.push({
      from: text.slice(word.start, end),
      to: digit,
      head: head.raw,
      context: contextAround(text, word.start, end),
    });
    // Слова, вошедшие в составное число, второй раз не рассматриваем.
    i = last;
  }

  if (edits.length === 0) return { text, replacements: [] };

  let out = "";
  let cursor = 0;
  for (const edit of edits) {
    out += text.slice(cursor, edit.start) + edit.value;
    cursor = edit.end;
  }
  out += text.slice(cursor);

  return { text: out, replacements };
}
