"use client";

import { Toaster } from "sonner";
import { CheckCircle2, AlertCircle, Info } from "lucide-react";

// Единая точка отрисовки ВСЕХ уведомлений приложения.
//
// Как было. Тостов в проекте два вида, и выглядели они по-разному:
//   * sonner — 75 вызовов toast(...) по всему коду, рисовались сверху
//     (position="top-center") цветными плашками richColors;
//   * собственный .sc-toast в SearchApp — тёмная градиентная плашка, тоже
//     сверху, со своим таймером и своей вёрсткой.
// На телефоне верхняя позиция — худшая из возможных: плашка налезала на
// статус-бар и Dynamic Island, а до крестика приходилось тянуться через весь
// экран. Плюс два разных оформления в одном приложении читаются как недоделка.
//
// Как стало. Рендерер один — этот. Собственный .sc-toast удалён, SearchApp
// зовёт тот же sonner. Все 75 существующих вызовов toast(...) менять не
// пришлось: они и так шли в единственный <Toaster>, а вид задаётся здесь и в
// globals.css (секция «Уведомления»).
//
// Позиция — снизу, НАД таб-баром: высота таб-бара считается той же формулой,
// что и в .tab-bar (var(--tab-bar-h) + env(safe-area-inset-bottom)), поэтому
// тост не перекрывает навигацию ни на телефоне с домашним индикатором, ни без
// него. Под статус-баром тост не появляется никогда — снизу его там просто нет.
//
// Отступ задан и пропом offset, и правилом в CSS: sonner подставляет offset в
// собственную переменную, а страховка в CSS гарантирует нужное значение, даже
// если версия библиотеки поменяет внутреннее имя переменной.

// Позицию контейнера задаёт CSS (globals.css, секция «Уведомления»), а не проп
// offset — и это выстраданное решение, а не небрежность. Проп offset у sonner
// участвует во внутренней математике стопки: скаляр прикладывается ко всем
// четырём сторонам (карточку сносило на 72px вправо за экран), а объект с
// bottom ломал вертикальный якорь — карточка уезжала вниз под экран. Оба
// случая поймал прогон в превью. С offset = 0 библиотека считает свою стопку
// от нижнего края как обычно, а вверх над таб-баром её поднимает одно правило
// CSS: bottom: calc(var(--tab-bar-h) + env(safe-area-inset-bottom) + 12px).

const ICON_SIZE = 20;

export default function AppToaster() {
  return (
    <Toaster
      position="bottom-center"
      offset={0}
      mobileOffset={0}
      closeButton
      // richColors выключен намеренно: он красит всю карточку в цвет статуса.
      // По макету карточка белая всегда, а статус несёт только иконка слева.
      icons={{
        success: <CheckCircle2 size={ICON_SIZE} color="var(--color-accent)" />,
        error: <AlertCircle size={ICON_SIZE} color="var(--color-danger)" />,
        warning: <AlertCircle size={ICON_SIZE} color="var(--color-warning)" />,
        info: <Info size={ICON_SIZE} color="var(--color-accent)" />,
      }}
      // Иконку по умолчанию (для простых toast("...") без типа, а их в коде
      // большинство) здесь задать нельзя: у sonner в ToastIcons есть только
      // ключи success/info/warning/error/loading/close, а ToastOptions поля
      // icon не имеет вовсе. Поэтому дефолтная зелёная галочка дорисовывается
      // в CSS — см. правило с :has([data-icon]) в globals.css.
    />
  );
}
