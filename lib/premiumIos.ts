// Правило App Store 3.1.1 в одном месте.
//
// Внутри нативного iOS-приложения нельзя показывать ничего, что ведёт к оплате
// мимо Apple: ни цен, ни кнопок «Оплатить», ни ссылок на /premium и /oferta.
// Условие простое, но оно нужно в пяти местах (подвал, шторка лимита, профиль,
// сами страницы /premium и /oferta) — и повторять его строкой
// `env === "native-ios"` в каждом означало бы, что шестое место однажды его
// забудет. Здесь же лежит и тест.
//
// Проверка ИМЕННО по среде, а не по гео, дате или аккаунту: прятать что-то от
// проверяющих Apple «хитро» нельзя, правило должно быть одно для всех.

import type { InstallEnv } from "@/lib/installEnv";

/**
 * Запрещено ли на этой среде показывать цены, кнопки оплаты и ссылки на них.
 *
 * "unknown" (сервер и кадр гидрации) считается РАЗРЕШЁННЫМ сознательно: иначе
 * в HTML первого ответа не было бы страницы «Премиум», а она обязана
 * индексироваться и открываться роботом платёжного сервиса. Цена — один кадр
 * в приложении до гидрации, после которого NativeIosGuard уводит на Главную.
 */
export function isPaymentUiBlocked(env: InstallEnv): boolean {
  return env === "native-ios";
}
