-- ============================================================================
-- Статус жалобы: возможность ОТКЛОНИТЬ жалобу в админке.
-- Запускать в Supabase SQL Editor (New query → Run). Идемпотентно.
--
-- Дополняет supabase_community_post_reports.sql (та миграция уже прогнана).
--
-- Зачем колонка. Два из трёх статусов в админке выводятся из существующих
-- данных и хранения не требуют:
--   «открыта»    — жалоба есть, пост всё ещё approved;
--   «пост скрыт» — community_posts.status = 'rejected'.
-- А вот «отклонена» (модератор посмотрел и решил пост оставить) — это решение
-- человека, из данных оно не выводится никак. Под него и нужна колонка.
--
-- Модель безопасности не меняется: таблица по-прежнему под RLS с НУЛЁМ политик,
-- писать в неё может только сервер на service_role (роут /api/admin/reports,
-- закрытый админ-сессией).
--
-- Код устойчив к отсутствию этой колонки: пока SQL не прогнан, вкладка «Жалобы»
-- работает и показывает статусы «открыта»/«пост скрыт», а кнопка «Отклонить
-- жалобу» честно отвечает, что нужна миграция. После прогона всё включается
-- само, без изменений кода.
--
-- Откат:
--   alter table public.community_post_reports drop column if exists dismissed_at;
-- ============================================================================

alter table public.community_post_reports
  add column if not exists dismissed_at timestamptz;

comment on column public.community_post_reports.dismissed_at is
  'Когда модератор отклонил жалобу (оставил пост). NULL = жалоба не отклонена.';

-- Частичный индекс под сортировку «открытые выше закрытых»: в выборке админки
-- открытые жалобы (dismissed_at is null) идут первыми и их всегда меньшинство.
create index if not exists community_post_reports_open_created_idx
  on public.community_post_reports (created_at desc)
  where dismissed_at is null;
