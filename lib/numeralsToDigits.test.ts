import { describe, expect, it } from "vitest";

import { numeralsToDigits } from "./numeralsToDigits";

function convert(text: string): string {
  return numeralsToDigits(text).text;
}

describe("numeralsToDigits — заменяет количества", () => {
  it("время", () => {
    expect(convert("Жарьте десять минут.")).toBe("Жарьте 10 минут.");
    expect(convert("Оставьте на два часа.")).toBe("Оставьте на 2 часа.");
    expect(convert("Варите в течение пяти минут.")).toBe("Варите в течение 5 минут.");
  });

  it("единицы измерения", () => {
    expect(convert("Добавьте две ложки муки.")).toBe("Добавьте 2 ложки муки.");
    expect(convert("Всыпьте три столовые ложки сахара.")).toBe("Всыпьте 3 столовые ложки сахара.");
    expect(convert("Налейте один стакан воды.")).toBe("Налейте 1 стакан воды.");
  });

  it("продукты", () => {
    expect(convert("Разбейте четыре яйца.")).toBe("Разбейте 4 яйца.");
    expect(convert("Возьмите два зубчика чеснока.")).toBe("Возьмите 2 зубчика чеснока.");
  });

  it("полтора — это 1,5 через запятую", () => {
    expect(convert("Толщиной полтора сантиметра.")).toBe("Толщиной 1,5 сантиметра.");
    expect(convert("Полторы ложки соли.")).toBe("1,5 ложки соли.");
  });

  it("заглавная буква в начале предложения не мешает", () => {
    expect(convert("Две ложки муки — и тесто готово.")).toBe("2 ложки муки — и тесто готово.");
  });

  it("диапазон «две-три минуты»", () => {
    expect(convert("Жарьте две-три минуты.")).toBe("Жарьте 2-3 минуты.");
  });

  it("составные числительные собираются целиком", () => {
    // Духовку в рецептах включают именно так, и «двести 20 градусов» —
    // ровно та ошибка, которую поймал первый прогон по каталогу.
    expect(convert("Включите духовку на двести двадцать градусов.")).toBe("Включите духовку на 220 градусов.");
    expect(convert("Разогрейте до ста восьмидесяти градусов.")).toBe("Разогрейте до 180 градусов.");
    expect(convert("Двадцать пять минут в духовке.")).toBe("25 минут в духовке.");
    expect(convert("Сто пятьдесят миллилитров воды.")).toBe("150 миллилитров воды.");
  });

  it("дефис — это диапазон, а не составное число", () => {
    expect(convert("Жарьте пять–шесть минут.")).toBe("Жарьте 5–6 минут.");
    expect(convert("Нужно двенадцать–четырнадцать листьев.")).toBe("Нужно 12–14 листьев.");
  });

  it("несколько замен в одной строке", () => {
    expect(convert("Два яйца и три ложки муки.")).toBe("2 яйца и 3 ложки муки.");
  });
});

describe("numeralsToDigits — НЕ трогает", () => {
  it("порядковые числительные", () => {
    expect(convert("Первый слой — картофель.")).toBe("Первый слой — картофель.");
    expect(convert("Вторая сковорода не нужна.")).toBe("Вторая сковорода не нужна.");
    expect(convert("Третью часть оставьте.")).toBe("Третью часть оставьте.");
  });

  it("«одна из», «один из»", () => {
    expect(convert("Одна из самых простых закусок.")).toBe("Одна из самых простых закусок.");
    expect(convert("Один из вариантов — запечь.")).toBe("Один из вариантов — запечь.");
  });

  it("«один» не рядом с мерой — это «единственный», а не количество", () => {
    expect(convert("Одна сковорода и полчаса времени.")).toBe("Одна сковорода и полчаса времени.");
    expect(convert("Готовится в одной сковороде.")).toBe("Готовится в одной сковороде.");
    expect(convert("Выложите в один слой.")).toBe("Выложите в один слой.");
    // А перед мерой — заменяем.
    expect(convert("Варите один час.")).toBe("Варите 1 час.");
    expect(convert("Полейте одной ложкой масла.")).toBe("Полейте 1 ложкой масла.");
  });

  it("числительное не рядом с предметом", () => {
    expect(convert("Одним движением переверните.")).toBe("Одним движением переверните.");
    expect(convert("Держите одной рукой.")).toBe("Держите одной рукой.");
    expect(convert("Это блюдо на все сто.")).toBe("Это блюдо на все сто.");
  });

  it("слова, похожие на числительные", () => {
    expect(convert("Сторона должна подрумяниться.")).toBe("Сторона должна подрумяниться.");
    expect(convert("Стоит попробовать.")).toBe("Стоит попробовать.");
  });

  it("то, что уже цифрами", () => {
    expect(convert("Жарьте 3–4 минуты с каждой стороны.")).toBe("Жарьте 3–4 минуты с каждой стороны.");
  });

  it("пустой текст и мусор", () => {
    expect(convert("")).toBe("");
    expect(numeralsToDigits(null as unknown as string).text).toBe("");
    expect(numeralsToDigits("").replacements).toEqual([]);
  });
});

describe("numeralsToDigits — отчёт для проверки", () => {
  it("на каждую замену видно слово, цифру, предмет и контекст", () => {
    const result = numeralsToDigits("Творог разомните, добавьте две ложки муки и жарьте десять минут.");
    expect(result.replacements).toHaveLength(2);
    expect(result.replacements[0]).toMatchObject({ from: "две", to: "2", head: "ложки" });
    expect(result.replacements[1]).toMatchObject({ from: "десять", to: "10", head: "минут" });
    expect(result.replacements[0].context).toContain("две ложки");
  });

  it("без замен текст возвращается тем же", () => {
    const text = "Первый слой — картофель.";
    const result = numeralsToDigits(text);
    expect(result.text).toBe(text);
    expect(result.replacements).toEqual([]);
  });
});
