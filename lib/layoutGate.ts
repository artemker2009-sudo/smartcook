// Где прячется «обвязка» приложения: таб-бар, футер, онбординг.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Раньше эти правила жили в двух местах сразу: серверный
// root-layout считал их из заголовка x-pathname, а TabBar — из usePathname на
// клиенте. Две копии одного условия уже разъезжались: при клиентской (soft)
// навигации серверный вариант НЕ пересчитывается, потому что root-layout при
// переходе между своими детьми не перерендеривается. Из-за этого таб-бар
// залипал в комнате банкета и перекрывал переключатель «Меню/Чат» (PR #58), а
// футер с онбордингом болели тем же, просто заметно это было меньше.
//
// Теперь правило ровно одно и лежит здесь. Считают его только клиентские
// компоненты по usePathname — то есть на каждой навигации заново.
//
// Файл намеренно без "use client": это чистые функции без состояния, и такой
// модуль спокойно импортируется и клиентом, и (если однажды понадобится)
// сервером. Директива "use client" здесь была бы вредна — см. грабли с
// рантайм-константами в lib/articles.ts.

/** Админка — своя вёрстка, вся обвязка сайта там лишняя. */
export function isAdminRoute(pathname: string): boolean {
  return pathname.startsWith("/admin");
}

/**
 * Комната банкета (/party/<id>) — полноэкранный рабочий экран со скроллом чата
 * и меню. Список банкетов (/parties) и форма создания (/party/create) — обычные
 * страницы, обвязку сохраняют.
 */
export function isPartyRoom(pathname: string): boolean {
  return pathname.startsWith("/party/") && pathname !== "/party/create";
}

/** Скрыта ли обвязка (таб-бар + футер) на этом маршруте. */
export function isChromeHidden(pathname: string): boolean {
  return isAdminRoute(pathname) || isPartyRoom(pathname);
}

/**
 * Скрыт ли ТОЛЬКО футер (таб-бар остаётся). Пока это «Премиум» и её экраны
 * оплаты: страница сделана по утверждённому макету и заканчивается собственным
 * блоком реквизитов. Общий футер под ним повторял бы те же ФИО, ИНН, почту и
 * телефон второй раз подряд — ровно на той странице, которую открывает
 * проверяющий платёжного сервиса.
 *
 * Таб-бар не трогаем: уйти со страницы человек должен уметь.
 */
export function isFooterHidden(pathname: string): boolean {
  return isChromeHidden(pathname) || pathname === "/premium" || pathname.startsWith("/premium/");
}
