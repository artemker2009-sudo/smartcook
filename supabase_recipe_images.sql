-- Что делает миграция:
--   1) Заводит Storage-бакет recipe-images с ПУБЛИЧНЫМ ЧТЕНИЕМ.
--   2) Добавляет колонку recipes.image_url text null.
--
-- ВАЖНО (урок #25): сначала прогнать эту миграцию в проде, потом мержить код.
-- Пока колонки/бакета нет, код деградирует мягко (рецепты без картинки), но
-- explicit-select на несуществующую колонку image_url отдаст 400 (PostgREST) —
-- поэтому колонка ДОЛЖНА появиться раньше кода.
--
-- Рецепт дня (app/api/daily/route.ts) в этой миграции НЕ трогаем: он эфемерный
-- (unstable_cache, без строки в БД, меняется каждый день), картинку под моделью
-- «1 раз на рецепт / только из админки» к нему прикрутить нельзя. Таблица
-- daily_recipes не используется — колонку туда не добавляем.

-- ── 1. Колонка ────────────────────────────────────────────────────────────────
-- Аддитивная nullable-колонка. RLS НЕ трогаем: наследует политики таблицы
-- recipes (см. supabase_recipes_social_rls.sql). image_url — публичная ссылка на
-- файл в публичном бакете, секрета не содержит, поэтому её попадание в
-- публичные explicit-select (страница рецепта, лента) безопасно.
alter table public.recipes
  add column if not exists image_url text;

comment on column public.recipes.image_url is
  'Публичная ссылка на сгенерированную ИИ картинку блюда (бакет recipe-images). '
  'null = картинки нет, UI ничего не показывает. Пишется только сервером '
  '(service_role) из админки.';

-- Проверка, что колонка появилась:
--   select column_name from information_schema.columns
--    where table_name = 'recipes' and column_name = 'image_url';

-- ── 2. Storage-бакет ────────────────────────────────────────────────────────
-- ОСОЗНАННОЕ РЕШЕНИЕ: чтение бакета recipe-images ПУБЛИЧНОЕ. Картинки блюд не
-- приватные — это иллюстрации к общедоступным рецептам, они и так показываются
-- всем на странице рецепта/в ленте. Публичный бакет = картинки раздаёт CDN
-- Supabase без подписанных URL (быстрый SSR, кэш на edge).
--
-- ЗАПИСЬ/УДАЛЕНИЕ — только service_role (серверная генерация из админки).
-- Политик storage.objects на insert/update/delete для anon/authenticated НЕ
-- создаём: их отсутствие и есть запрет (RLS на storage.objects включён по
-- умолчанию). service_role ходит в обход RLS, поэтому серверу отдельная политика
-- на запись не нужна. Публичное ЧТЕНИЕ обеспечивает флаг public=true у бакета
-- (Supabase сам вешает read-политику для публичных бакетов).
insert into storage.buckets (id, name, public)
values ('recipe-images', 'recipe-images', true)
on conflict (id) do update set public = true;

