"use client";

import { useEffect } from "react";

/**
 * Проверка обновлений установленного PWA — БЕЗ перезагрузки страницы.
 *
 * Зачем компонент вообще нужен. Браузер сам ходит за новым sw.js только при
 * навигации или примерно раз в сутки. iOS в standalone при повторном открытии
 * ВОЗОБНОВЛЯЕТ замороженный документ, навигации не происходит — и установленное
 * приложение может очень долго жить на старом бандле. Поэтому при загрузке и при
 * каждом возврате в приложение мы явно просим браузер сходить и проверить.
 *
 * Что изменилось после приёмки. Раньше здесь был `window.location.reload()` по
 * событию controllerchange, а SW собирался с `skipWaiting`. Вместе это давало
 * ровно ту жалобу, ради которой файл переписан: «зашёл на сайт — через десять
 * секунд он сам обновился». Десять секунд — время скачать и разложить precache
 * новой версии; после этого она захватывала открытую страницу и мы её
 * перезагружали. Посреди режима «Готовим!» или наполовину набранного списка это
 * просто потеря того, что человек делал.
 *
 * Как теперь. `skipWaiting: false` (next.config.ts) — новая версия скачивается и
 * ВСТАЁТ В ОЧЕРЕДЬ, не трогая открытую страницу. Активируется она сама, когда
 * закроется последний клиент на старой версии, то есть при следующем спокойном
 * заходе. Никаких принудительных перезагрузок отсюда больше не уходит.
 *
 * Осознанная плата: обновление доезжает на один запуск позже. Для приложения,
 * где человек стоит в магазине с открытым списком, это верный размен.
 */
export default function PWAUpdater() {
  useEffect(() => {
    if (typeof navigator === "undefined" || !("serviceWorker" in navigator)) return;

    const checkForUpdate = () => {
      navigator.serviceWorker
        .getRegistration()
        .then((reg) => reg?.update())
        .catch(() => {
          /* офлайн/сеть — не критично, попробуем при следующем возврате */
        });
    };

    checkForUpdate();

    const onVisibility = () => {
      if (document.visibilityState === "visible") checkForUpdate();
    };
    document.addEventListener("visibilitychange", onVisibility);

    return () => {
      document.removeEventListener("visibilitychange", onVisibility);
    };
  }, []);

  return null;
}
