// Локальный словарь частых русских продуктов + классификация слова.
// НИКАКИХ обращений к OpenAI: разбор диктовки и вставленного текста должен
// работать мгновенно, оффлайн и бесплатно.
//
// Зачем: наша аудитория диктует и пишет без запятых — «молоко яйца хлеб
// тефтели». Разделителями служат сами названия продуктов: новая позиция
// начинается со знакомого продукта, а незнакомые слова-описания
// («охлаждённое», «без кожи и костей») остаются в текущей позиции.
//
// Сопоставление по ОСНОВЕ (stem), а не по точному совпадению: «молока»,
// «молоко», «молоком» → одна основа «молок». Это грубая морфология без
// словаря форм, зато предсказуемая и в пару килобайт.

// Окончания режем от длинных к коротким; основа не короче 3 символов, иначе
// «чая» → «ча» ловило бы половину языка.
const RU_ENDINGS = ["ами", "ями", "ах", "ях", "ов", "ев", "ой", "ей", "ом", "ем", "ью", "ы", "и", "а", "я", "о", "е", "у", "ю", "ь"];

const MIN_STEM = 3;

/** Основа слова: нижний регистр, ё→е, срезанное окончание. */
export function stem(word: string): string {
  const w = word.toLowerCase().replace(/ё/g, "е");
  for (const end of RU_ENDINGS) {
    if (w.length - end.length >= MIN_STEM && w.endsWith(end)) return w.slice(0, -end.length);
  }
  return w;
}

// Прилагательные-описания: «куриное», «сливочное», «нарезной». Такое слово
// никогда не начинает новую позицию — иначе «куриное филе» развалилось бы.
// Исключения (существительные с прилагательным окончанием) ниже.
const ADJECTIVE_ENDINGS = ["ый", "ий", "ой", "ая", "яя", "ое", "ее", "ые", "ие", "ого", "его", "ому", "ему", "ым", "им", "ых", "их", "ую", "юю"];

const ADJECTIVE_EXCEPTIONS = new Set([
  "мороженое", "пирожное", "шампанское", "жаркое", "заливное", "первое", "второе",
]);

export function looksLikeAdjective(word: string): boolean {
  const w = word.toLowerCase().replace(/ё/g, "е");
  if (ADJECTIVE_EXCEPTIONS.has(w)) return false;
  return ADJECTIVE_ENDINGS.some((end) => w.length - end.length >= MIN_STEM && w.endsWith(end));
}

