// @ts-ignore
const withPWA = require("@ducanh2912/next-pwa").default({
  dest: "public",
  cacheOnFrontEndNav: true,
  aggressiveFrontEndNavCaching: true,
  // ПЕРЕЗАГРУЗКА ПРИ ВОЗВРАТЕ СЕТИ — ВЫКЛЮЧЕНА.
  // Опция вешает location.reload() на событие online. На телефоне оно
  // срабатывает не только когда интернет реально пропадал: переключение
  // Wi-Fi↔LTE, выход из лифта, пробуждение экрана — и страница перезагружается
  // сама. Для режима «Готовим!» и наполовину набранного списка это потеря
  // состояния на ровном месте.
  reloadOnOnline: false,
  swcMinify: true,
  disable: process.env.NODE_ENV === "development",
  workboxOptions: {
    disableDevLogs: true,
    // НОВАЯ ВЕРСИЯ ЖДЁТ, А НЕ ВРЫВАЕТСЯ.
    //
    // Было skipWaiting: true — свежий SW активировался сразу и (вместе с
    // clientsClaim) забирал управление УЖЕ ОТКРЫТОЙ страницей. Дальше
    // PWAUpdater ловил controllerchange и перезагружал её. Отсюда и «зашёл на
    // сайт, через десять секунд он сам обновился»: десять секунд — это время
    // скачать и разложить precache новой версии.
    //
    // Вторая, менее заметная беда того же переключателя: cleanupOutdatedCaches
    // вычищает старые чанки прямо под работающей страницей. Живой сеанс потом
    // спотыкается на подгрузке куска, которого больше нет, и Next.js спасается
    // полной перезагрузкой — снова посреди готовки.
    //
    // Теперь новый SW встаёт в очередь и активируется сам, когда закрыт
    // последний использующий старую версию клиент, то есть при следующем
    // естественном заходе. Плата честная: обновление доезжает на один запуск
    // позже. Ради несбиваемого «Готовим!» это правильный размен.
    //
    // ПЕРЕСМОТРЕНО 5 сентября 2026 после аварии «страница без стилей» — и
    // решение ОСТАВЛЕНО ПРЕЖНИМ. Возврат skipWaiting: true вылечил бы застрявший
    // кэш, но ценой ровно того бага, который чинили в PR #76: свежий SW
    // забирает уже открытую страницу, cleanupOutdatedCaches вычищает чанки под
    // работающим сеансом, Next спасается полной перезагрузкой — посреди
    // готовки или наполовину набранного списка.
    //
    // Вместо этого проблема закрыта с двух других сторон, и обе не трогают
    // открытую страницу:
    //   * окно устаревшего HTML сжато с 24 часов до 30 минут (см. sc-pages);
    //   * 404 на ассете сбрасывает кэш HTML, и СЛЕДУЮЩАЯ навигация приходит из
    //     сети (см. плагин на sc-static).
    // Если позже захочется доставлять обновления быстрее — правильный путь не
    // skipWaiting, а ненавязчивое предложение «Доступна новая версия» с
    // кнопкой, где перезагрузку запускает человек, а не воркер.
    skipWaiting: false,
    clientsClaim: true,
    cleanupOutdatedCaches: true,
    // Явные правила рантайм-кэша. По умолчанию next-pwa кэширует /api —
    // здесь мы это ЗАПРЕЩАЕМ. Кэшируем только статику (shell/иконки/картинки).
    runtimeCaching: [
      // API, авторизация, Supabase, OpenAI, Метрика — ТОЛЬКО сеть, без кэша.
      {
        urlPattern: ({ url }: { url: URL }) =>
          url.pathname.startsWith("/api/") ||
          url.pathname.startsWith("/auth") ||
          /supabase\.co$/.test(url.hostname) ||
          /openai\.com$/.test(url.hostname) ||
          /mc\.yandex\.(ru|com)$/.test(url.hostname),
        handler: "NetworkOnly",
      },
      // Статика Next (JS/CSS уже в precache, дублируем на всякий) — SWR.
      //
      // Здесь же лежит защита от аварии «страница без стилей», из-за которой
      // 5 сентября пришлось откатывать деплой. Механика была такая:
      //   1) Vercel на тарифе Hobby удаляет ассеты старой сборки СРАЗУ — старый
      //      хеш CSS начинает отдавать 404 (проверено curl-ом на боевом);
      //   2) sc-pages мог отдать HTML прошлой сборки (NetworkFirst с таймаутом
      //      3 секунды срабатывает на любой медленной сети);
      //   3) этот старый HTML тянет удалённый CSS → 404 → страница вообще без
      //      стилей. А без CSS `position: fixed` не существует: таб-бар и
      //      плавающие кнопки падают в обычный поток и уезжают вверх при
      //      скролле. Ровно тот симптом, который видел пользователь.
      {
        urlPattern: ({ url }: { url: URL }) => url.pathname.startsWith("/_next/static/"),
        handler: "StaleWhileRevalidate",
        options: {
          cacheName: "sc-static",
          // Лимитов тут не было вовсе. Ставим НАМЕРЕННО ЩЕДРЫЕ: маленький
          // maxEntries тут не «гигиена», а вред — он вытеснит из кэша CSS
          // предыдущей сборки, и офлайн-заход на старом HTML сломается точно
          // так же, как от 404. 300 записей — это несколько сборок Next
          // (у одной ~60–120 файлов), 30 суток — заведомо больше, чем живёт
          // любой наш кэш HTML. Смысл лимита только один: не дать кэшу расти
          // бесконечно на устройстве.
          expiration: { maxEntries: 300, maxAgeSeconds: 30 * 24 * 60 * 60 },
          plugins: [
            {
              // Не класть в кэш ничего, кроме 200. Без этого SWR радостно
              // закэширует сам 404 — и поломка станет постоянной: воркер
              // будет отдавать «нет такого файла» уже из кэша, даже когда
              // сеть в порядке.
              cacheWillUpdate: async ({ response }: { response: Response }) =>
                response && response.status === 200 ? response : null,
              // 404 на ассете = HTML и статика из разных сборок. Чиним причину:
              // выбрасываем кэш HTML, чтобы СЛЕДУЮЩАЯ навигация пришла из сети
              // и принесла согласованную пару HTML+CSS. Страницу под
              // пользователем НЕ перезагружаем — этот баг мы уже лечили в
              // PR #76 и повторять его не будем.
              //
              // Сносим ТОЛЬКО sc-pages. Трогать sc-static тем же движением
              // заманчиво, но вредно: (1) виноват старый HTML, а не ассеты —
              // они лежат под хешами и лишние записи просто не запрашиваются;
              // (2) удаление кэша прямо во время работы SWR роняет параллельный
              // cache.put в уже удалённый кэш. Меньше действий — меньше поводов
              // сломать воркер, а он общий для всего сайта.
              fetchDidSucceed: async ({ response }: { response: Response }) => {
                if (response && response.status === 404) {
                  await caches.delete("sc-pages");
                }
                return response;
              },
            },
          ],
        },
      },
      // Иконки/картинки шелла — SWR.
      {
        urlPattern: ({ request }: { request: Request }) => request.destination === "image",
        handler: "StaleWhileRevalidate",
        options: {
          cacheName: "sc-images",
          expiration: { maxEntries: 60, maxAgeSeconds: 7 * 24 * 60 * 60 },
        },
      },
      // Навигации (шелл страниц) — сеть в приоритете, кэш как офлайн-фолбэк.
      //
      // Было 24 часа. Ровно это и есть окно, в котором пользователь получает
      // HTML прошлой сборки со ссылкой на уже удалённый CSS. Совсем убирать
      // кэш навигаций не стали: список покупок живёт в localStorage и реально
      // работает без сети, а без этого кэша офлайн-заход на /shopping давал бы
      // не список, а экран «нет соединения» — потеря функции ради страховки.
      //
      // 30 минут — компромисс: перезагрузка страницы, метро, лифт и прочая
      // мигающая сеть по-прежнему обслуживаются из кэша, а окно совпадения с
      // деплоем сократилось в 48 раз. Остаток закрывает плагин на 404 выше:
      // даже если в это окно попасть, следующая навигация будет из сети.
      {
        urlPattern: ({ request }: { request: Request }) => request.mode === "navigate",
        handler: "NetworkFirst",
        options: {
          cacheName: "sc-pages",
          networkTimeoutSeconds: 3,
          expiration: { maxEntries: 32, maxAgeSeconds: 30 * 60 },
          plugins: [
            {
              // Не кэшировать ошибки: 404/500 в кэше навигаций означал бы, что
              // человек получает сломанную страницу из кэша и после того, как
              // сервер починился.
              cacheWillUpdate: async ({ response }: { response: Response }) =>
                response && response.status === 200 ? response : null,
            },
          ],
        },
      },
    ],
  },
});

/** @type {import('next').NextConfig} */
const nextConfig = {
  eslint: {
    ignoreDuringBuilds: true,
  },
  typescript: {
    ignoreBuildErrors: true,
  },
  images: {
    unoptimized: true,
  },
  // Digital Asset Links для TWA обязаны лежать по каноническому пути
  // /.well-known/assetlinks.json. Отдаём их из динамического роута (содержимое
  // из env ASSETLINKS_JSON), а не статикой — отпечаток подписи появится только
  // после сборки пакета. Rewrite (а не redirect) сохраняет исходный URL, как
  // того требует проверка Play/RuStore.
  async rewrites() {
    return [
      {
        source: "/.well-known/assetlinks.json",
        destination: "/api/assetlinks",
      },
    ];
  },
  // Легаси share-ссылки (/?recipeId=… и /search?recipeId=…) уводим на быстрый
  // серверный маршрут /recipe/:id ещё до загрузки клиента — иначе они снова
  // тянули бы монолит SearchApp (задача T). Редирект на уровне сервера/edge,
  // так что старые ссылки открываются так же быстро, как новые.
  async redirects() {
    return [
      {
        source: "/",
        has: [{ type: "query", key: "recipeId", value: "(?<rid>\\d+)" }],
        destination: "/recipe/:rid",
        permanent: false,
      },
      {
        source: "/search",
        has: [{ type: "query", key: "recipeId", value: "(?<rid>\\d+)" }],
        destination: "/recipe/:rid",
        permanent: false,
      },
    ];
  },
};

export default withPWA(nextConfig);
