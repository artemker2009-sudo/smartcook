// Разбор голосового ввода продуктов в список покупок. Пользователь называет
// продукты подряд («молоко… хлеб… огурцы»); разделители — паузы (приходят как
// пробелы или отдельные результаты распознавания), союз «и», запятые.
//
// Чистая функция без побочных эффектов — легко тестируется (voiceParse.test.ts).
// Каждое слово трактуется как отдельный продукт: для списка покупок продукты
// почти всегда 1–2 слова, а надёжно определить границы многословных названий по
// голосу нельзя. Ошибочный/склеенный чип пользователь убирает крестиком до
// добавления, поэтому режем агрессивно, но предсказуемо.

// Служебные слова, которые не являются продуктами.
const STOPWORDS = new Set([
  "и", "да", "а", "но", "ещё", "еще", "потом", "так", "ну", "это", "вот", "же", "бы",
]);

export function parseVoiceTranscript(text: string): string[] {
  if (typeof text !== "string" || !text.trim()) return [];

  const tokens = text
    .toLowerCase()
    .replace(/[.!?;:«»"()]/g, " ") // знаки препинания → пробел
    .split(/[,\n]|\sи\s/g) // явные разделители: запятая, перевод строки, « и »
    .join(" ")
    .split(/\s+/)
    .map((t) => t.trim())
    .filter(Boolean);

  const out: string[] = [];
  for (const token of tokens) {
    if (STOPWORDS.has(token)) continue;
    if (token.length < 2) continue; // отсекаем «э», отдельные буквы-паразиты
    if (out.includes(token)) continue; // дедуп в пределах одной фразы
    out.push(token);
  }
  return out;
}
