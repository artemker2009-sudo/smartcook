-- ПЕРЕНОС ГОСТЕВЫХ РЕЦЕПТОВ В АККАУНТ (PR 2). Подготовка БД.
--
-- Задача: при регистрации/входе рецепты и избранное, сохранённые анонимно на
-- этом устройстве, должны переехать в аккаунт. Сейчас `cook_user_id`
-- перезаписывается на user.id, а строки со старым гостевым id остаются в БД
-- недоступными никому и никогда.
--
-- Красная линия задачи: ни один рецепт не теряется. Дубль лучше потери.
-- Отсюда обе строчки ниже.
--
-- ЗАЧЕМ claimed_from. Перенос — это UPDATE session_id, то есть операция,
-- которая затирает прежнего владельца. Без записи «откуда переехало» откат
-- невозможен В ПРИНЦИПЕ: старый идентификатор больше нигде не хранится (в
-- localStorage устройства он к этому моменту уже перезаписан). Колонка делает
-- перенос обратимым одним запросом и заодно даёт аудит: сколько строк реально
-- переехало и откуда.
--
-- Второе назначение — защита в глубину: серверный роут забирает только строки
-- с `claimed_from is null`, поэтому строка переносится РОВНО ОДИН РАЗ. Даже
-- если кто-то раздобудет чужой гостевой id, повторно увести уже перенесённый
-- рецепт он не сможет.
--
-- ЗАЧЕМ индекс. И сам перенос (`where session_id = ...`), и чтение истории
-- (`recipes_for_session`) ходят по session_id. На сегодняшних 348 строках это
-- незаметно, но перенос делает такие запросы регулярными.
--
-- Колонка в RLS не участвует и клиенту не видна: после
-- supabase_recipes_session_id_privacy.sql роли anon/authenticated имеют
-- поколоночный SELECT на явный список, куда claimed_from не входит. Узкие
-- списки колонок (SSR-страница рецепта, recipes_for_session) её не запрашивают,
-- так что добавление ничего не ломает.

alter table public.recipes add column if not exists claimed_from text;

create index if not exists recipes_session_id_idx on public.recipes (session_id);


-- ============================================================================
-- Проверка: колонка есть, индекс есть.
-- ============================================================================
select
  (select count(*) from information_schema.columns
    where table_schema = 'public' and table_name = 'recipes' and column_name = 'claimed_from') as has_claimed_from,
  (select count(*) from pg_indexes
    where schemaname = 'public' and tablename = 'recipes' and indexname = 'recipes_session_id_idx') as has_index;


