import { Info } from "lucide-react";

// Дисклеймер App Store 1.4.1 (physical harm): приложение, которое выдаёт
// рецепты, обязано прямо предупредить, что состав нужно проверять — рецепт
// сгенерирован моделью и может содержать аллерген.
//
// Сознательно ОДНА строка, а не баннер. Полный текст про ИИ и ответственность
// уже есть в /about, /terms и в описании в App Store; здесь нужен короткий
// маркер ровно в двух точках, где человек принимает решение готовить:
// в карточке рецепта и на входе в режим готовки. Баннер на этих экранах читался
// бы как ошибка и его бы пролистывали не глядя.
//
// Текст живёт в одном месте, чтобы две копии не разошлись при первой же правке.
export const AI_RECIPE_DISCLAIMER = "Рецепт составлен ИИ — проверяйте состав на аллергены";

export default function AiRecipeDisclaimer({ className }: { className?: string }) {
  return (
    <p className={className ? `ai-disclaimer ${className}` : "ai-disclaimer"}>
      <Info size={14} aria-hidden />
      <span>{AI_RECIPE_DISCLAIMER}</span>
    </p>
  );
}
