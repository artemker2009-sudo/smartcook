export type WordKind = "product" | "unit" | "quantity" | "connector" | "preposition" | "other";

/** Чистое число: «2», «1.5», «10%», «2шт» уже разлеплено до этого. */
function isNumber(word: string): boolean {
  return /^\d+([.,]\d+)?%?$/.test(word);
}

export function classifyWord(rawWord: string): WordKind {
  const word = rawWord.toLowerCase().replace(/ё/g, "е").replace(/^[^0-9а-яa-z]+|[^0-9а-яa-z%]+$/g, "");
  if (!word) return "other";
  if (isNumber(word) || NUMERAL_WORDS.has(word)) return "quantity";

  const s = stem(word);
  // Единицы раньше продуктов: «пачка», «стакан» не должны считаться продуктом.
  if (UNIT_STEMS.has(s)) return "unit";
  if (PREPOSITION_WORDS.has(word)) return "preposition";
  if (CONNECTOR_WORDS.has(word)) return "connector";
  // Прилагательное-описание продуктом не считаем ни при каких условиях.
  if (looksLikeAdjective(word)) return "other";
  if (PRODUCT_STEMS.has(s)) return "product";
  return "other";
}

export function isProductWord(word: string): boolean {
  return classifyWord(word) === "product";
}
