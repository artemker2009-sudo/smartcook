-- Бакет recipe-images: принимать ТОЛЬКО картинки нужных типов.
--
-- ЗАЧЕМ. С PR #148 файлы этого бакета отдаются со СВОЕГО домена
-- (smartcook.pro/img/…). До сих пор бакет принимал файл любого типа
-- (allowed_mime_types = NULL). Если бы в него когда-нибудь попал HTML или SVG
-- со скриптом, он исполнился бы уже в контексте нашего сайта — рядом со
-- списками покупок и сессией. Запись в бакет сейчас закрыта отсутствием
-- политик (аноним проверен рантаймом 21.09.2026: 403 AccessDenied), это
-- ограничение — вторая линия обороны на случай, если политику однажды
-- откроют кликом в дашборде.
--
-- ПОЧЕМУ НЕ 'image/*'. Шаблон пропускает image/svg+xml, а SVG умеет
-- исполнять скрипты — ровно тот вектор, от которого закрываемся. Поэтому
-- список явный.
--
-- ЧТО ЭТО НЕ СЛОМАЕТ (проверено по коду 21.09.2026). Запись в recipe-images
-- в приложении ОДНА: lib/recipeImage.ts, upload(path, webp,
-- { contentType: "image/webp", upsert: true }) через service_role —
-- генерация картинок блюд, рецептов и «Идей». Удалений, переносов и копий в
-- этом бакете код не делает, .list() — чтение. Остальные загрузки приложения
-- идут в ДРУГИЕ бакеты (avatars, feed_photos, recipe_photos) и этой правкой
-- не затрагиваются. Ограничение Supabase проверяет и загрузки через
-- service_role, поэтому это настоящий запрет, а не только для анонима.
--
-- Уже лежащие файлы не трогаются: проверка действует только на новые
-- загрузки. Все 105 существующих файлов — image/webp.
--
-- ОТКАТ: update storage.buckets set allowed_mime_types = null
--        where id = 'recipe-images';

update storage.buckets
set allowed_mime_types = array['image/webp', 'image/png', 'image/jpeg']
where id = 'recipe-images';

-- Проверка: должна вернуться одна строка со списком из трёх типов.
select id, public, allowed_mime_types, file_size_limit
from storage.buckets
where id = 'recipe-images';
