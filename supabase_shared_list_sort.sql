-- ============================================================================
-- Раскладка общего списка по отделам магазина — сохранение результата.
-- Запускать целиком в Supabase SQL Editor (New query → Run) ДО мержа кода.
-- Идемпотентно, безопасно перезапускать. Ничего не удаляет.
--
-- ЗАЧЕМ. У личного списка результат раскладки лежит в localStorage устройства
-- (поле `sort` в smartcook_shopping_lists_v2, см. lib/shoppingLists.ts). Для
-- общего списка этого мало: разложил один — увидеть должны ВСЕ участники, ровно
-- как галочки. Значит результат должен жить на сервере, рядом со списком.
--
-- ПОЧЕМУ НЕ БЕЗ КОЛОНКИ. Рассматривались и отвергнуты:
--   * хранить у каждого на устройстве — не доедет до остальных, это и есть
--     задача;
--   * разослать broadcast'ом без сохранения — переживёт ровно до перезагрузки,
--     а кто в этот момент не онлайн, не увидит вовсе;
--   * пересчитывать на каждом устройстве — это отдельный вызов OpenAI на
--     каждого участника (лишние деньги) и разные результаты у разных людей.
--
-- ЧТО ИМЕННО ХРАНИМ. Ту же пару, что и локальный кэш:
--   sort_sig     — подпись набора позиций, для которого раскладка считалась;
--   sort_groups  — сами группы (отдел → названия позиций).
-- Подпись нужна, чтобы понимать, что раскладка устарела: добавили или убрали
-- позицию — подпись разъехалась, и интерфейс снова предлагает разложить.
-- Вычёркивание галочки подпись НЕ меняет (см. listSignature в
-- lib/shoppingList.ts), поэтому поход по магазину раскладку не сбрасывает.
--
-- БЕЗОПАСНОСТЬ не меняется: RLS на shared_lists уже включён и политик у неё
-- ноль (supabase_shared_shopping_lists.sql). Новые колонки наследуют ровно тот
-- же режим — anon и authenticated не читают и не пишут их, работает только
-- сервис-роль из серверных роутов. Никаких новых политик этот файл не
-- добавляет и существующие не трогает.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 1. Колонки
-- ----------------------------------------------------------------------------

alter table public.shared_lists
  add column if not exists sort_sig text,
  add column if not exists sort_groups jsonb;

-- ----------------------------------------------------------------------------
-- 2. Ограничения — вторая линия обороны
-- ----------------------------------------------------------------------------
-- Группы собираются на СЕРВЕРЕ из оригинальных названий позиций (buildGroups в
-- lib/shoppingList.ts): модель возвращает только номер отдела на индекс, поэтому
-- переименовать или подсунуть лишнюю позицию она физически не может. Эти CHECK'и
-- — страховка на случай, если будущий роут забудут пропустить через buildGroups:
-- в колонку нельзя будет положить ни объект вместо массива, ни мегабайтную
-- подпись.

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'shared_lists_sort_groups_is_array') then
    alter table public.shared_lists
      add constraint shared_lists_sort_groups_is_array
      check (sort_groups is null or jsonb_typeof(sort_groups) = 'array');
  end if;

  if not exists (select 1 from pg_constraint where conname = 'shared_lists_sort_sig_len') then
    alter table public.shared_lists
      add constraint shared_lists_sort_sig_len
      check (sort_sig is null or char_length(sort_sig) <= 4000);
  end if;
end $$;

-- Про 4000: подпись — это названия позиций в нижнем регистре через «|».
-- Потолок списка 60 позиций по 50 символов даёт максимум ~3060 символов, так
-- что 4000 с запасом покрывает честный случай и отсекает мусор.

-- ----------------------------------------------------------------------------
-- 3. Самопроверка
-- ----------------------------------------------------------------------------
-- Выполнится вместе с файлом. Ожидаем две строки — sort_groups (jsonb) и
-- sort_sig (text), обе nullable, и по-прежнему rls_enabled = true, policies = 0.

select column_name, data_type, is_nullable
from information_schema.columns
where table_schema = 'public'
  and table_name = 'shared_lists'
  and column_name in ('sort_sig', 'sort_groups')
order by column_name;

select
  c.relname as table_name,
  c.relrowsecurity as rls_enabled,
  (select count(*) from pg_policies p
    where p.schemaname = 'public' and p.tablename = c.relname) as policies
from pg_class c
join pg_namespace n on n.oid = c.relnamespace
where n.nspname = 'public' and c.relname = 'shared_lists';

