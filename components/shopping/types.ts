import type { ShoppingGroup } from "@/lib/shoppingList";

/**
 * Позиция в том виде, в каком её рисует экран списка.
 *
 * Намеренно НЕ ShoppingItem и НЕ SharedItem: экран один на локальный и на
 * общий список, а эти два типа живут в разных хранилищах и расходятся в
 * деталях (source против checkedBy). Приведение делает хозяин списка —
 * он же знает, откуда взялась подпись.
 */
export type RowItem = {
  id: string;
  /** Полное имя, как лежит в хранилище. Для показа делится splitQuantity. */
  name: string;
  checked: boolean;
  /** Мелкая серая строка под названием: «для «Борщ»» или «купил(а) Артём». */
  note?: string | null;
  /**
   * Чем подпись «склеивается» с соседями. Одинаковый ключ у идущих подряд
   * строк = одна группа, и подпись рисуется только у ПЕРВОЙ из них.
   *
   * Нужно для продуктов из рецепта: восемь позиций «Гречки с курицей» давали
   * восемь одинаковых строчек «для «Гречка с курицей»» — они занимали пол
   * экрана и говорили одно и то же. У подписей, которые к КАЖДОЙ строке
   * относятся по-своему («купил(а) Артём» в общем списке), ключа нет, и они
   * показываются у всех.
   */
  noteGroup?: string | null;
};

/** Режим раскладки: что показывает иконка в шапке и что делает нажатие. */
export type SortState =
  /** Раскладки нет вообще — первое нажатие посчитает её (вызов модели). */
  | "none"
  /** Раскладка есть и совпадает с текущим набором — переключение мгновенное. */
  | "ready"
  /** Позиции менялись после раскладки — нажатие пересчитает её. */
  | "stale";

export type ListScreenSort = {
  state: SortState;
  /** Группы из валидного кэша. null, когда state !== "ready". */
  groups: ShoppingGroup[] | null;
  /** Человек выбрал смотреть по отделам. */
  grouped: boolean;
  /** Идёт вызов раскладки. */
  busy: boolean;
  error: string | null;
  onToggle: () => void;
  /**
   * Пересчитать устаревшую раскладку (state === "stale"). Отдельное действие,
   * а не автоматика: это вызов модели, и он должен быть по нажатию.
   */
  onRecompute: () => void;
};
