// Событие «повторный тап по уже активной вкладке таб-бара».
//
// Отдельный модуль, потому что у события два несвязанных участника: таб-бар
// его шлёт, раздел — слушает. Класть общую константу в один из них значило бы
// заставить навигацию знать про ленту (или наоборот).
//
// Поведение привычное по любому приложению с таб-баром: тап по активной
// вкладке возвращает раздел в начало и обновляет его.

export const TAB_RESELECT_EVENT = "smartcook:tab-reselect";

export type TabReselectDetail = { href: string };

/**
 * Считать ли тап по вкладке «повторным» — то есть отменить переход и
 * обновить раздел на месте.
 *
 * ТОЛЬКО на корне раздела. Подсветка вкладки идёт по startsWith, и на экране
 * рецепта /ideas/<slug> вкладка «Идеи» тоже активна. Раньше перехват решал
 * по той же подсветке, и тап по «Идеям» на рецепте отменял переход в ленту,
 * а слушать событие было некому — лента не смонтирована. Кнопка просто не
 * работала. На вложенном экране тап по вкладке — это обычный переход к
 * разделу, как в любом приложении с таб-баром.
 */
export function isTabReselect(pathname: string, href: string): boolean {
  return pathname === href;
}
