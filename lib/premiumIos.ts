// Правило App Store 3.1.1 в одном месте.
//
// Внутри нативного iOS-приложения нельзя показывать ничего, что ведёт к оплате
// мимо Apple: ни цен, ни кнопок «Оплатить», ни ссылок на /premium и /oferta.
// Условие простое, но оно нужно в пяти местах (подвал, шторка лимита, профиль,
// сами страницы /premium и /oferta) — и повторять его строкой
// `env === "native-ios"` в каждом означало бы, что шестое место однажды его
// забудет. Здесь же лежит и тест.
//
// Проверка ИМЕННО по среде, а не по гео, дате или аккаунту: прятать что-то от
// проверяющих Apple «хитро» нельзя, правило должно быть одно для всех.

// Относительные пути: алиас @/ в vitest не резолвится, а файл покрыт тестами.
import type { InstallEnv } from "./installEnv";
import { pluralPodbor } from "./premiumPeriod";
import { PREMIUM_PLANS, formatPriceRub } from "./premiumPlans";

/**
 * Запрещено ли на этой среде показывать цены, кнопки оплаты и ссылки на них.
 *
 * "unknown" (сервер и кадр гидрации) считается РАЗРЕШЁННЫМ сознательно: иначе
 * в HTML первого ответа не было бы страницы «Премиум», а она обязана
 * индексироваться и открываться роботом платёжного сервиса. Цена — один кадр
 * в приложении до гидрации, после которого NativeIosGuard уводит на Главную.
 */
export function isPaymentUiBlocked(env: InstallEnv): boolean {
  return env === "native-ios";
}


/**
 * Тексты шторки «подборы закончились». Здесь, а не внутри компонента, ровно
 * ради теста: требование «в iOS нет ни цен, ни слова „Премиум“, ни ссылок» —
 * это утверждение про ТЕКСТ, и проверять его надо текстом, а не глазами.
 */
export type PodborLimitCopy = {
  title: string;
  text: string;
  /** Подпись главной кнопки. */
  action: string;
  /** Куда ведёт кнопка. null — просто закрыть шторку (вариант iOS). */
  href: string | null;
  /** Подпись ссылки «закрыть». null — её нет (вариант iOS). */
  dismiss: string | null;
};

export function podborLimitCopy(env: InstallEnv, limit: number): PodborLimitCopy {
  if (isPaymentUiBlocked(env)) {
    return {
      title: "Подборы на эту неделю закончились",
      text: "Новые — в понедельник.",
      action: "Понятно",
      href: null,
      dismiss: null,
    };
  }

  // «169 ₽ в год» — цена берётся из самого тарифа, а не вписана строкой:
  // прайс правится в lib/premiumPlans.ts, и подпись обязана съезжать вместе с
  // ним. Раньше здесь было «от N ₽» по самому дешёвому тарифу; теперь тариф со
  // сроком ровно один, и честнее назвать его прямо.
  const year = PREMIUM_PLANS.find((p) => p.days === 365) ?? PREMIUM_PLANS[0];

  return {
    title: "Подборы на этой неделе закончились",
    text:
      `Бесплатно — ${limit} ${pluralPodbor(limit)} в неделю, новые — в понедельник. ` +
      `С Премиумом — без лимита, ${formatPriceRub(year.priceRub)} в год.`,
    action: "Оформить Премиум",
    href: "/premium",
    dismiss: "Подожду до понедельника",
  };
}
