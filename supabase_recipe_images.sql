-- на INSERT/UPDATE/DELETE. Любая запись — только через service_role ключ с
-- сервера. Если позже понадобится клиентская загрузка — добавлять политику
-- ЯВНО и с оглядкой на инциденты №1/№2 (RLS по умолчанию открыт на таблицах).
